const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const { mkdir } = require('node:fs/promises')
;(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
  const base=process.argv[2]||'http://localhost:3107'
  await mkdir('.bto-backups/qa',{recursive:true})
  try {
    for(const width of [1440,390]) {
      const page=await browser.newPage({viewport:{width,height:1000}})
      const errors=[]; page.on('pageerror', e=>errors.push(e.message))
      await page.goto(base+'/btob',{waitUntil:'domcontentloaded'})
      const region=page.getByRole('region',{name:'パッケージ形状のサンプル一覧'})
      await region.scrollIntoViewIfNeeded()
      await region.locator('img').evaluateAll(imgs=>imgs.forEach(i=>i.loading='eager'))
      await region.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())))
      assert.equal(await region.locator('article').count(),14)
      await page.getByRole('button',{name:'次のパッケージを見る'}).click()
      await page.waitForTimeout(650)
      assert(await region.evaluate(e=>e.scrollLeft)>0,'Arrow must scroll')
      await region.focus(); await page.keyboard.press('End')
      await region.evaluate(e=>e.scrollLeft=e.scrollWidth)
      await page.waitForTimeout(500)
      await region.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())))
      assert(await region.locator('img').evaluateAll(imgs=>imgs.every(i=>i.naturalWidth>0)))
      await region.evaluate(e=>e.scrollLeft=0)
      await page.waitForTimeout(500)
      await page.locator('section[aria-labelledby="package-showcase-heading"]').screenshot({path:`.bto-backups/qa/gallery-${width}.png`})
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No page overflow')
      await page.locator('#bto-form details').evaluate(e=>e.open=true)
      await page.locator('#bto-form details img').evaluateAll(imgs=>imgs.forEach(i=>i.loading='eager'))
      await page.locator('#bto-form details img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())))
      await page.locator('#bto-form details').screenshot({path:`.bto-backups/qa/extra-packages-${width}.png`})
      assert.deepEqual(errors,[])
      console.log(`PASS gallery ${width}: 14 cards, loaded images, scroll, no overflow/errors`)
      await page.close()
    }
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
